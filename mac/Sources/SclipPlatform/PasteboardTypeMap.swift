import AppKit
import Foundation
import SclipCore

/// macOS pasteboard UTI -> kanonik format ve bayrak eslemesi (B-8.8.4, B-8.8.7, E31).
public enum PasteboardTypeMap {
    public static let utf8PlainText = NSPasteboard.PasteboardType("public.utf8-plain-text")
    public static let html = NSPasteboard.PasteboardType("public.html")
    public static let rtf = NSPasteboard.PasteboardType("public.rtf")
    public static let png = NSPasteboard.PasteboardType("public.png")
    public static let jpeg = NSPasteboard.PasteboardType("public.jpeg")
    public static let gif = NSPasteboard.PasteboardType("com.compuserve.gif")
    public static let webp = NSPasteboard.PasteboardType("org.webmproject.webp")
    public static let svg = NSPasteboard.PasteboardType("public.svg-image")
    public static let pdf = NSPasteboard.PasteboardType("com.adobe.pdf")
    public static let tiff = NSPasteboard.PasteboardType("public.tiff")
    public static let fileURL = NSPasteboard.PasteboardType("public.file-url")

    public static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    public static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    public static let directMappings: [(NSPasteboard.PasteboardType, CanonicalFormat)] = [
        (utf8PlainText, .plainText),
        (html, .html),
        (rtf, .rtf),
        (png, .png),
        (jpeg, .jpeg),
        (gif, .gif),
        (webp, .webp),
        (svg, .svg),
        (pdf, .pdf),
    ]

    private static let promiseRawTypes: Set<String> = [
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-name",
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.PromisedFileURL",
        "com.apple.pasteboard.PromisedFileName",
        "com.apple.pasteboard.PromisedFileContentType",
    ]

    public static func flags(for types: [NSPasteboard.PasteboardType]) -> Set<ClipFlag> {
        var result: Set<ClipFlag> = []
        for type in types {
            if type == concealed {
                result.insert(.concealed)
            } else if type == transient || type == autoGenerated {
                result.insert(.transient)
            }
        }
        return result
    }

    public static func isSensitive(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        !flags(for: types).isEmpty
    }

    public static func hasFiles(_ types: [NSPasteboard.PasteboardType]) -> Bool {
        let readablePromises = Set(NSFilePromiseReceiver.readableDraggedTypes)
        for type in types {
            if type == fileURL || promiseRawTypes.contains(type.rawValue)
                || readablePromises.contains(type.rawValue)
            {
                return true
            }
        }
        return false
    }
}
