import AppKit
import SclipCore
import SclipPlatform
import XCTest

final class PasteboardReaderTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        super.setUp()
        pasteboard = NSPasteboard(name: .init("sclip-test-\(UUID().uuidString)"))
        pasteboard.clearContents()
    }

    override func tearDown() {
        pasteboard?.releaseGlobally()
        pasteboard = nil
        super.tearDown()
    }

    func testPlainTextMapsToCanonical() {
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in [] }
        pasteboard.setString("hello sclip", forType: .string)

        let clip = reader.readClip()
        XCTAssertEqual(clip.items.count, 1)
        let data = clip.items.first?.formats[.plainText]
        XCTAssertEqual(data.flatMap { String(data: $0, encoding: .utf8) }, "hello sclip")
        XCTAssertTrue(clip.flags.isEmpty)
    }

    func testTiffBecomesPng() throws {
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in [] }
        let image = NSImage(size: NSSize(width: 4, height: 4))
        image.lockFocus()
        NSColor.systemRed.setFill()
        NSBezierPath(rect: NSRect(x: 0, y: 0, width: 4, height: 4)).fill()
        image.unlockFocus()
        let tiffData = try XCTUnwrap(image.tiffRepresentation)

        pasteboard.declareTypes([.tiff], owner: nil)
        XCTAssertTrue(pasteboard.setData(tiffData, forType: .tiff))

        let clip = reader.readClip()
        XCTAssertEqual(clip.items.count, 1)
        let pngData = try XCTUnwrap(clip.items.first?.formats[.png])
        // PNG magic header: 89 50 4E 47 0D 0A 1A 0A
        XCTAssertEqual(Array(pngData.prefix(8)), [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A])
    }

    func testConcealedFlag() {
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in [] }
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        pasteboard.declareTypes([.string, concealed], owner: nil)
        pasteboard.setString("secret", forType: .string)
        pasteboard.setData(Data(), forType: concealed)

        let state = reader.currentState()
        XCTAssertTrue(state.sensitive)

        let clip = reader.readClip()
        XCTAssertTrue(clip.flags.contains(.concealed))
    }

    func testTransientFlag() {
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in [] }
        let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let autoGen = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        pasteboard.declareTypes([.string, transient, autoGen], owner: nil)
        pasteboard.setString("otp", forType: .string)
        pasteboard.setData(Data(), forType: transient)
        pasteboard.setData(Data(), forType: autoGen)

        let state = reader.currentState()
        XCTAssertTrue(state.sensitive)

        let clip = reader.readClip()
        XCTAssertTrue(clip.flags.contains(.transient))
    }

    func testFileURLsSetHasFilesAndAreReadWithoutConsuming() {
        var promiseCalls = 0
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in
            promiseCalls += 1
            return []
        }
        let fileURL = URL(fileURLWithPath: "/tmp/sclip-reader-test.txt")
        XCTAssertTrue(pasteboard.writeObjects([fileURL as NSURL]))

        let stateBefore = reader.currentState()
        XCTAssertTrue(stateBefore.hasFiles)

        let urls = reader.readFiles(destination: EntryID(raw: 1))
        XCTAssertEqual(urls.map(\.path), [fileURL.path])
        XCTAssertEqual(promiseCalls, 0)

        // Pasteboard types and changeCount remain intact after reading.
        let stateAfter = reader.currentState()
        XCTAssertTrue(stateAfter.hasFiles)
        XCTAssertEqual(stateAfter.change, stateBefore.change)
        let typesAfter = pasteboard.types ?? []
        XCTAssertTrue(typesAfter.contains(.fileURL))
    }

    func testChangeCountReflectsWrites() {
        let reader = PasteboardReader(pasteboard: pasteboard) { _, _ in [] }
        let initial = reader.currentState().change

        pasteboard.clearContents()
        pasteboard.setString("one", forType: .string)
        let first = reader.currentState().change
        XCTAssertGreaterThan(first, initial)

        pasteboard.clearContents()
        pasteboard.setString("two", forType: .string)
        let second = reader.currentState().change
        XCTAssertGreaterThan(second, first)
    }

    func testPromiseFallbackRespectsDestinationNilForSensitive() {
        let promisedType = NSPasteboard.PasteboardType("com.apple.pasteboard.promised-file-url")
        pasteboard.declareTypes([promisedType], owner: nil)
        pasteboard.setData(Data("1".utf8), forType: promisedType)

        var receivedIDs: [EntryID] = []
        let expectedURL = URL(fileURLWithPath: "/tmp/promised.png")
        let reader = PasteboardReader(pasteboard: pasteboard) { _, id in
            receivedIDs.append(id)
            return [expectedURL]
        }

        XCTAssertTrue(reader.currentState().hasFiles)
        // destination == nil (B-8.4.4): must not resolve promises.
        XCTAssertTrue(reader.readFiles(destination: nil).isEmpty)
        XCTAssertTrue(receivedIDs.isEmpty)

        // destination != nil: resolves promises into destination.
        let id = EntryID(raw: 42)
        XCTAssertEqual(reader.readFiles(destination: id), [expectedURL])
        XCTAssertEqual(receivedIDs, [id])
    }
}
